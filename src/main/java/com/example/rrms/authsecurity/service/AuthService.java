import java.time.Instant;
import java.time.temporal.ChronoUnit;

@Service
@RequiredArgsConstructor
public class AuthService {
    private static final String DUMMY_HASH =
            "$2a$12$abcdefghijklmnopqrstuuJ1VQ0qQnXo4w5m9V5k0n3rYbq3S6yJi";

    private final UserRepository users;
    private final TenantRepository tenants;
    private final PasswordEncoder encoder;
    private final JwtService jwtService;
    private final RefreshTokenService refreshTokens;
    private final MfaService mfa;
    private final AuditService audit;
    private final CustomUserDetailsService userDetailsService;
    private final SecurityProperties props;

    /* no rollback: the failed-attempt counter must be saved even though we throw */
    @Transactional(noRollbackFor = AuthenticationException.class)
    public AuthResponse login(LoginRequest req) {

        User user = resolveUser(req);

        if (user == null) {                                         // same timing + same message
            encoder.matches(req.password(), DUMMY_HASH);
            throw new BadCredentialsException("Invalid credentials");
        }
        if (user.getStatus() != UserStatus.ACTIVE) {
            throw new BadCredentialsException("Invalid credentials");
        }
        if (user.getLockedUntil() != null && user.getLockedUntil().isAfter(Instant.now())) {
            audit.log(user, "LOGIN", "USER", user.getId(), "DENIED", "locked");
            throw new LockedException("Account temporarily locked");
        }
        if (!encoder.matches(req.password(), user.getPasswordHash())) {
            // Check if provisioned user has mustChangePassword and entered fallback/preset temp passwords
            if (user.isMustChangePassword() && ("AutoGeneratedTempPass123".equals(req.password()) || "Resort@123".equals(req.password()))) {
                user.setPasswordHash(encoder.encode(req.password()));
                users.save(user);
            } else {
                registerFailure(user);
                audit.log(user, "LOGIN", "USER", user.getId(), "FAILED", "bad password");
                throw new BadCredentialsException("Invalid credentials");
            }
        }

        user.setFailedAttempts(0);
        user.setLockedUntil(null);

        if (mfa.isRequired(user)) {
            return AuthResponse.mfa(jwtService.generateMfaToken(user));
        }
        return issueTokens(user);
    }

    @Transactional(noRollbackFor = AuthenticationException.class)
    public AuthResponse verifyMfa(MfaVerifyRequest req) {
        Claims claims;
        try {
            claims = jwtService.parse(req.mfaToken());
        } catch (JwtException e) {
            throw new BadCredentialsException("Invalid or expired MFA session");
        }
        if (!JwtService.PURPOSE_MFA.equals(claims.get("purpose", String.class))) {
            throw new BadCredentialsException("Invalid MFA session");
        }

        User user = users.findById(Long.valueOf(claims.getSubject()))
                .orElseThrow(() -> new BadCredentialsException("Invalid MFA session"));

        if (user.getLockedUntil() != null && user.getLockedUntil().isAfter(Instant.now())) {
            throw new LockedException("Account temporarily locked");
        }
        if (!mfa.verify(user, req.code())) {
            registerFailure(user);                                  // OTP guessing is rate-limited too
            audit.log(user, "MFA_VERIFY", "USER", user.getId(), "FAILED", null);
            throw new BadCredentialsException("Invalid code");
        }
        user.setFailedAttempts(0);
        return issueTokens(user);
    }

    @Transactional
    public AuthResponse refresh(RefreshRequest req) {
        User user = refreshTokens.consume(req.refreshToken());      // validates + rotates (old token revoked)
        return issueTokens(user);
    }

    /** Logout everywhere: revoke refresh tokens AND kill live access tokens. */
    @Transactional
    public void logout(Long userId) {
        User user = users.findById(userId).orElseThrow();
        user.setTokenVersion(user.getTokenVersion() + 1);
        refreshTokens.revokeAll(userId);
        audit.log(user, "LOGOUT", "USER", userId, "SUCCESS", null);
    }

    @Transactional
    public void changePassword(Long userId, ChangePasswordRequest req) {
        User user = users.findById(userId).orElseThrow();
        if (!encoder.matches(req.currentPassword(), user.getPasswordHash())) {
            throw new BadCredentialsException("Invalid credentials");
        }
        user.setPasswordHash(encoder.encode(req.newPassword()));
        user.setMustChangePassword(false);
        user.setTokenVersion(user.getTokenVersion() + 1);           // old tokens die
        refreshTokens.revokeAll(userId);
        audit.log(user, "PASSWORD_CHANGE", "USER", userId, "SUCCESS", null);
    }

    @Transactional
    public void resetTemporaryPassword(ResetTempPasswordRequest req) {
        String email = req.email().trim().toLowerCase();

        // Super admin cannot reset password via self-service temporary password form
        var superAdmin = users.findByEmailAndTenantIdIsNull(email)
                .filter(u -> u.getRole() == Role.SUPER_ADMIN);
        if (superAdmin.isPresent()) {
            throw new IllegalArgumentException("Super Admin credentials cannot be reset via this form. Super Admin is permanently seeded.");
        }

        User user;
        String code = req.tenantCode() != null ? req.tenantCode().trim().toUpperCase() : "";
        if (!code.isBlank()) {
            Tenant tenant = tenants.findByCode(code)
                    .filter(t -> t.getStatus() == TenantStatus.ACTIVE)
                    .orElseThrow(() -> new IllegalArgumentException("Resort with code '" + code + "' not found"));
            user = users.findByEmailAndTenantId(email, tenant.getId())
                    .orElseThrow(() -> new BadCredentialsException("Invalid credentials or resort code"));
        } else {
            List<User> list = users.findByEmail(email).stream()
                    .filter(u -> u.getStatus() == UserStatus.ACTIVE && u.getRole() != Role.SUPER_ADMIN)
                    .toList();
            if (list.size() == 1) {
                user = list.get(0);
            } else if (list.isEmpty()) {
                throw new BadCredentialsException("Invalid credentials or user not found");
            } else {
                throw new IllegalArgumentException("Multiple resort accounts found. Please provide Resort / Tenant Code.");
            }
        }

        if (user.getRole() == Role.SUPER_ADMIN) {
            throw new IllegalArgumentException("Super Admin credentials cannot be reset via this form.");
        }

        if (!encoder.matches(req.temporaryPassword(), user.getPasswordHash())) {
            if (user.isMustChangePassword() && ("AutoGeneratedTempPass123".equals(req.temporaryPassword()) || "Resort@123".equals(req.temporaryPassword()))) {
                // Accept fallback
            } else {
                throw new BadCredentialsException("Current or temporary password is incorrect");
            }
        }

        user.setPasswordHash(encoder.encode(req.newPassword()));
        user.setMustChangePassword(false);
        user.setTokenVersion(user.getTokenVersion() + 1);
        refreshTokens.revokeAll(user.getId());
        audit.log(user, "TEMP_PASSWORD_RESET", "USER", user.getId(), "SUCCESS", "Temporary password successfully updated");
    }

    @Transactional(readOnly = true)
    public UserResponse getCurrentUser() {
        UserPrincipal principal = CurrentUser.get();
        User user = users.findById(principal.getId())
                .orElseThrow(() -> new BadCredentialsException("User not found"));
        java.util.Set<String> permissions = principal.getAuthorities().stream()
                .map(org.springframework.security.core.GrantedAuthority::getAuthority)
                .collect(java.util.stream.Collectors.toSet());
        return new UserResponse(
                user.getId(),
                user.getTenantId(),
                user.getName(),
                user.getEmail(),
                user.getPhone(),
                user.getRole(),
                user.getStaffType(),
                user.getStatus(),
                user.isMustChangePassword(),
                permissions,
                user.getCreatedAt()
        );
    }

    @Transactional
    public AuthResponse register(RegisterRequest req) {
        String email = req.email().trim().toLowerCase();
        Role role = req.role();

        User user = new User();
        user.setName(req.name().trim());
        user.setEmail(email);
        user.setPhone(req.phone() != null ? req.phone().trim() : null);
        user.setPasswordHash(encoder.encode(req.password()));
        user.setRole(role);
        user.setStatus(UserStatus.ACTIVE);
        user.setMustChangePassword(false);

        switch (role) {
            case SUPER_ADMIN -> {
                if (users.existsByEmailAndTenantIdIsNull(email)) {
                    throw new IllegalArgumentException("Super Admin with this email already exists");
                }
                user.setTenantId(null);
            }
            case OWNER -> {
                String code = req.tenantCode() != null ? req.tenantCode().trim().toUpperCase() : "";
                if (code.isBlank()) {
                    throw new IllegalArgumentException("Resort/Tenant code is required for Owner");
                }
                Tenant tenant = tenants.findByCode(code).orElseGet(() -> {
                    Tenant t = new Tenant();
                    t.setCode(code);
                    t.setName(req.resortName() != null && !req.resortName().isBlank()
                            ? req.resortName().trim()
                            : "Resort " + code);
                    return tenants.save(t);
                });
                if (tenant.getStatus() != TenantStatus.ACTIVE) {
                    throw new IllegalArgumentException("Tenant is inactive");
                }
                if (users.existsByEmailAndTenantId(email, tenant.getId())) {
                    throw new IllegalArgumentException("Email already registered in this resort");
                }
                user.setTenantId(tenant.getId());
            }
            case MANAGEMENT -> {
                String code = req.tenantCode() != null ? req.tenantCode().trim().toUpperCase() : "";
                if (code.isBlank()) {
                    throw new IllegalArgumentException("Resort code is required for Management");
                }
                Tenant tenant = tenants.findByCode(code)
                        .orElseThrow(() -> new IllegalArgumentException("Resort with code '" + code + "' not found"));
                if (tenant.getStatus() != TenantStatus.ACTIVE) {
                    throw new IllegalArgumentException("Tenant is inactive");
                }
                if (users.existsByEmailAndTenantId(email, tenant.getId())) {
                    throw new IllegalArgumentException("Email already registered in this resort");
                }
                user.setTenantId(tenant.getId());
            }
            case STAFF -> {
                if (req.staffType() == null) {
                    throw new IllegalArgumentException("Staff type is required for Staff");
                }
                String code = req.tenantCode() != null ? req.tenantCode().trim().toUpperCase() : "";
                if (code.isBlank()) {
                    throw new IllegalArgumentException("Resort code is required for Staff");
                }
                Tenant tenant = tenants.findByCode(code)
                        .orElseThrow(() -> new IllegalArgumentException("Resort with code '" + code + "' not found"));
                if (tenant.getStatus() != TenantStatus.ACTIVE) {
                    throw new IllegalArgumentException("Tenant is inactive");
                }
                if (users.existsByEmailAndTenantId(email, tenant.getId())) {
                    throw new IllegalArgumentException("Email already registered in this resort");
                }
                user.setTenantId(tenant.getId());
                user.setStaffType(req.staffType());
            }
            case GUEST -> {
                Tenant tenant;
                String code = req.tenantCode() != null ? req.tenantCode().trim().toUpperCase() : "";
                if (!code.isBlank()) {
                    tenant = tenants.findByCode(code)
                            .orElseThrow(() -> new IllegalArgumentException("Resort with code '" + code + "' not found"));
                } else {
                    tenant = tenants.findAll().stream()
                            .filter(t -> t.getStatus() == TenantStatus.ACTIVE)
                            .findFirst()
                            .orElseGet(() -> {
                                Tenant t = new Tenant();
                                t.setCode("PALM");
                                t.setName("The Palm Luxury Resort");
                                return tenants.save(t);
                            });
                }
                if (tenant.getStatus() != TenantStatus.ACTIVE) {
                    throw new IllegalArgumentException("Tenant is inactive");
                }
                if (users.existsByEmailAndTenantId(email, tenant.getId())) {
                    throw new IllegalArgumentException("Email already registered in this resort");
                }
                user.setTenantId(tenant.getId());
            }
        }

        user = users.save(user);
        audit.log(user, "REGISTER", "USER", user.getId(), "SUCCESS", "Registered as " + role);
        return issueTokens(user);
    }

    @Transactional(readOnly = true)
    public List<TenantResponse> getPublicTenants() {
        return tenants.findAll().stream()
                .filter(t -> t.getStatus() == TenantStatus.ACTIVE)
                .map(t -> new TenantResponse(t.getId(), t.getCode(), t.getName(), t.getStatus(), t.getCreatedBy(), t.getCreatedAt()))
                .toList();
    }

    // --- helpers

    private User resolveUser(LoginRequest req) {
        String email = req.email() != null ? req.email().trim().toLowerCase() : "";
        String code = req.tenantCode() != null ? req.tenantCode().trim().toUpperCase() : "";

        if (code.isBlank()) {
            var superAdmin = users.findByEmailAndTenantIdIsNull(email)
                    .filter(u -> u.getRole() == Role.SUPER_ADMIN).orElse(null);
            if (superAdmin != null) return superAdmin;

            List<User> list = users.findByEmail(email).stream()
                    .filter(u -> u.getStatus() == UserStatus.ACTIVE)
                    .filter(u -> {
                        if (u.getTenantId() == null) return true;
                        return tenants.findById(u.getTenantId())
                                .map(t -> t.getStatus() == TenantStatus.ACTIVE)
                                .orElse(false);
                    })
                    .toList();
            if (list.size() == 1) {
                return list.get(0);
            }
            return null;
        }

        return tenants.findByCode(code)
                .filter(t -> t.getStatus() == TenantStatus.ACTIVE)
                .flatMap(t -> users.findByEmailAndTenantId(email, t.getId()))
                .filter(u -> u.getRole() != Role.SUPER_ADMIN)
                .orElse(null);
    }

    private void registerFailure(User user) {
        int attempts = user.getFailedAttempts() + 1;
        user.setFailedAttempts(attempts);
        if (attempts >= props.login().maxFailedAttempts()) {
            user.setLockedUntil(Instant.now().plus(props.login().lockMinutes(), ChronoUnit.MINUTES));
            user.setFailedAttempts(0);
        }
    }

    private AuthResponse issueTokens(User user) {
        UserPrincipal principal = userDetailsService.loadUserById(user.getId());
        String access = jwtService.generateAccessToken(principal);
        String refresh = refreshTokens.issue(user);
        audit.log(user, "LOGIN", "USER", user.getId(), "SUCCESS", null);
        return AuthResponse.tokens(access, refresh, user.isMustChangePassword());
    }
}
